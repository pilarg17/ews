# Corporate EWS / B01 Model Review | One independent Dataiku notebook cell
# Read-only queries. Does not load training history into Pandas.
import dataiku
from dataiku.core.sql import SQLExecutor2
from IPython.display import display

PROJECT = 'VALIDATIONEWSCORPORATEPORTFOLIODAILY'
conn = 'DEV_AA_TEAMS'
ex = SQLExecutor2(connection=conn)
results = '"RRG"."' + PROJECT + '_RESULTS_B01_DPD_RATING"'
tests = '"RRG"."' + PROJECT + '_TEST_RESULTS_B01_DPD_RATING"'
training = '"RRG"."' + PROJECT + '_EWS_TRAINING_B01_DPD_RATING"'

print('='*95)
print('B01 - OPTIMAL DPD / RATING / GCC THRESHOLDS')
print('='*95)
display(ex.query_to_df(f'''SELECT INDICATOR, THRESHOLD_A,THRESHOLD_B,
THRESHOLD_A_RATING_LABEL,THRESHOLD_B_RATING_LABEL,
N_TP,N_FP,N_FN,N_EVENTS,ACCURACY,COVERAGE,COVERAGE_2,COVERAGE_3,
AV_NR_DAY_ALERTS, MAX_DAILY_ALERTS,AV_NR_MON_ALERTS,MAX_MONTHLY_ALERTS,
TOTAL_COST,EXPOSURE_BASIS,CALIBRATION_STATUS
FROM {results} WHERE OPTIMAL=TRUE ORDER BY INDICATOR'''))

print('\n'+'='*95)
print('B01 - QA AND BUSINESS REVIEW')
print('='*95)
display(ex.query_to_df(f'''SELECT QA_TYPE,CHECK_NAME,CHECK_PASSED,CHECK_VALUE,EXPECTED_VALUE
FROM {tests} WHERE QA_TYPE<>'OPTIMAL_THRESHOLD'
ORDER BY QA_TYPE,CHECK_NAME'''))

print('\n'+'='*95)
print('B01 - CORPORATE DATA AVAILABILITY AT THE 10 MOST RECENT DPD SNAPSHOTS')
print('='*95)
display(ex.query_to_df(f'''SELECT TO_DATE(MAP_DTE) MAP_DTE,
COUNT(*) ROW_COUNT,
COUNT_IF(TGT_ANY_SAMEDAY=1) TARGET_POSITIVE,
COUNT_IF(TGT_ANY_SAMEDAY=0) TARGET_NEGATIVE,
COUNT_IF(TGT_ANY_SAMEDAY IS NULL) TARGET_UNKNOWN,
COUNT_IF(CLIENT_NOTCH IS NOT NULL) CLIENT_RATING_AVAILABLE,
COUNT_IF(GCC_NOTCH IS NOT NULL) GCC_RATING_AVAILABLE,
COUNT_IF(NOMINAL_KNOWN_LOANS=LOAN_COUNT AND LOAN_SOURCE_DUPLICATES=0
  AND NOMINAL_KNOWN_SUM>0) COMPLETE_NOMINAL_AVAILABLE
FROM {training}
WHERE LOAN_COUNT>0 AND HAS_VALID_ENTITY_HISTORY=1 AND DPD_MAX IS NOT NULL
GROUP BY 1 ORDER BY 1 DESC LIMIT 10'''))
print('\nAll queries read-only.')
