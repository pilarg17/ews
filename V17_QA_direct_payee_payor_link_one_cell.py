# V17 | READ ONLY | Check proposed direct PAYEE -> PAYOR link before changing recurring payers.
# ONE CELL in Dataiku Python notebook. No recipe or data changes.
import pandas as pd
from dataiku.core.sql import SQLExecutor2

ORACLE = 'PRD_BDWH'
SCHEMA = 'BDL_PAYMENT_PLY'
START = '2026-09-01'
END = '2026-10-01'
SAMPLE_MAX = 2000
ora = SQLExecutor2(connection=ORACLE)

meta = ora.query_to_df("""
SELECT TABLE_NAME,COLUMN_NAME FROM ALL_TAB_COLUMNS
WHERE OWNER='BDL_PAYMENT_PLY'
AND TABLE_NAME IN ('PAYEE_VW','PAYOR_VW','PAYOR_PAYEE_REF_VW')
AND COLUMN_NAME IN ('CREDIT_PAYMENT_ID','LINKED_DEBIT_PAYMENT_ID','DEBIT_PAYMENT_ID',
                    'CREDIT_VALUE_DATE','PAYMENT_DIRECTION','ORDER_GIVER_ACCOUNT',
                    'CREDIT_ACCOUNT_CUSTOMER_ID')
""")
meta.columns=[x.upper() for x in meta.columns]
found={name:set(g.COLUMN_NAME.astype(str).str.upper()) for name,g in meta.groupby('TABLE_NAME')}
requirements={
    'PAYEE_VW':{'CREDIT_PAYMENT_ID','LINKED_DEBIT_PAYMENT_ID','CREDIT_VALUE_DATE'},
    'PAYOR_VW':{'DEBIT_PAYMENT_ID'},
    'PAYOR_PAYEE_REF_VW':{'CREDIT_PAYMENT_ID','DEBIT_PAYMENT_ID'},
}
print('=== SOURCE_FIELDS ===',flush=True)
print(meta.to_csv(index=False,sep=';').strip(),flush=True)
missing={n:sorted(cols-found.get(n,set())) for n,cols in requirements.items() if cols-found.get(n,set())}
if missing:
    print('STOP | DIRECT_LINK_OR_REFERENCE_FIELDS_MISSING | '+str(missing),flush=True)
    print('NO RECIPES CHANGED',flush=True)
else:
    pred=("AND UPPER(TRIM(PAYMENT_DIRECTION))='INCOMING' " if
          'PAYMENT_DIRECTION' in found['PAYEE_VW'] else '')
    q="""
WITH P_SAMPLE AS (
 SELECT CREDIT_ID,DIRECT_DEBIT_ID FROM (
  SELECT TRIM(TO_CHAR(CREDIT_PAYMENT_ID)) CREDIT_ID,
         TRIM(TO_CHAR(LINKED_DEBIT_PAYMENT_ID)) DIRECT_DEBIT_ID
  FROM BDL_PAYMENT_PLY.PAYEE_VW
  WHERE CREDIT_VALUE_DATE>=DATE '{start}' AND CREDIT_VALUE_DATE<DATE '{end}'
    AND CREDIT_PAYMENT_ID IS NOT NULL {pred}
 ) WHERE ROWNUM<={cap}
), P AS (
 SELECT CREDIT_ID, MIN(DIRECT_DEBIT_ID) DIRECT_DEBIT_ID,
        COUNT(DISTINCT DIRECT_DEBIT_ID) N_DISTINCT_DIRECT_DEBITS
 FROM P_SAMPLE GROUP BY CREDIT_ID
), R AS (
 SELECT TRIM(TO_CHAR(r.CREDIT_PAYMENT_ID)) CREDIT_ID,
        MIN(TRIM(TO_CHAR(r.DEBIT_PAYMENT_ID))) REF_DEBIT_ID,
        COUNT(DISTINCT TRIM(TO_CHAR(r.DEBIT_PAYMENT_ID))) N_DISTINCT_REF_DEBITS
 FROM BDL_PAYMENT_PLY.PAYOR_PAYEE_REF_VW r
 JOIN P ON TRIM(TO_CHAR(r.CREDIT_PAYMENT_ID))=P.CREDIT_ID
 GROUP BY TRIM(TO_CHAR(r.CREDIT_PAYMENT_ID))
), D AS (
 SELECT P.CREDIT_ID,
        P.DIRECT_DEBIT_ID,P.N_DISTINCT_DIRECT_DEBITS,
        R.REF_DEBIT_ID,NVL(R.N_DISTINCT_REF_DEBITS,0) N_DISTINCT_REF_DEBITS
 FROM P LEFT JOIN R ON R.CREDIT_ID=P.CREDIT_ID
)
SELECT COUNT(*) N_CREDIT_PAYMENTS_SAMPLE,
 SUM(CASE WHEN DIRECT_DEBIT_ID IS NOT NULL THEN 1 ELSE 0 END) N_WITH_DIRECT_ID,
 SUM(CASE WHEN REF_DEBIT_ID IS NOT NULL THEN 1 ELSE 0 END) N_WITH_REFERENCE_ID,
 SUM(CASE WHEN DIRECT_DEBIT_ID IS NOT NULL AND REF_DEBIT_ID IS NOT NULL
           AND DIRECT_DEBIT_ID=REF_DEBIT_ID THEN 1 ELSE 0 END) N_SAME_DIRECT_AND_REF,
 SUM(CASE WHEN DIRECT_DEBIT_ID IS NOT NULL AND REF_DEBIT_ID IS NOT NULL
           AND DIRECT_DEBIT_ID<>REF_DEBIT_ID THEN 1 ELSE 0 END) N_CONFLICT_DIRECT_VS_REF,
 SUM(CASE WHEN DIRECT_DEBIT_ID IS NOT NULL AND REF_DEBIT_ID IS NULL THEN 1 ELSE 0 END) N_DIRECT_ONLY,
 SUM(CASE WHEN DIRECT_DEBIT_ID IS NULL AND REF_DEBIT_ID IS NOT NULL THEN 1 ELSE 0 END) N_REFERENCE_ONLY,
 SUM(CASE WHEN N_DISTINCT_DIRECT_DEBITS>1 THEN 1 ELSE 0 END) N_AMBIGUOUS_DIRECT,
 SUM(CASE WHEN N_DISTINCT_REF_DEBITS>1 THEN 1 ELSE 0 END) N_AMBIGUOUS_REFERENCE
FROM D
""".format(start=START,end=END,pred=pred,cap=SAMPLE_MAX)
    print('\n=== DIRECT_LINK_VS_REFERENCE_QA ===',flush=True)
    out=ora.query_to_df(q)
    out.columns=[x.upper() for x in out.columns]
    print(out.to_csv(index=False,sep=';',na_rep='NULL').strip(),flush=True)
    print('QA | SAMPLE_ONLY=YES | MONTH='+START+' | MAX_PAYEE_SOURCE_ROWS='+str(SAMPLE_MAX),flush=True)
    print('QA | CHECK_DIRECT_JOIN_PAYOR_ACCOUNT_COVERAGE_BEFORE_SOURCE_SWITCH',flush=True)
    print('QA | NO RECIPE_OR_BACKTEST_MODIFICATIONS',flush=True)
