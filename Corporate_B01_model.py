def q(value):
    value = str(value).replace("${projectKey}", PROJECT)
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value):
        raise ValueError("Invalid Snowflake identifier: " + repr(value))
    return '"' + value + '"'


